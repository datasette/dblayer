"""Regenerate src/errnames.h from a sqlite3.h: the name of every result code
(what Python's ``sqlite3.Error.sqlite_errorname`` reports).

    uv run python cworker/gen_errnames.py cworker/vendor/sqlite-amalgamation-*/sqlite3.h
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


def main(header: str) -> None:
    text = Path(header).read_text()
    start = text.index("#define SQLITE_OK ")
    end = text.index("#define SQLITE_OK_SYMLINK")
    names = re.findall(r"^#define (SQLITE_[A-Z_0-9]+)\s", text[start:end], re.M)
    names = [n for n in names if n != "SQLITE_OK_LOAD_PERMANENTLY"]
    out = [
        "/* Generated by cworker/gen_errnames.py from sqlite3.h: do not edit. */",
        "#ifndef DBLAYER_ERRNAMES_H",
        "#define DBLAYER_ERRNAMES_H",
        "static const struct { int code; const char *name; } ERRNAMES[] = {",
    ]
    for n in names:
        out.append(f"#ifdef {n}\n    {{{n}, \"{n}\"}},\n#endif")
    out += ["};", "#endif", ""]
    Path(__file__).with_name("src").joinpath("errnames.h").write_text("\n".join(out))
    print(f"{len(names)} result codes")


if __name__ == "__main__":
    main(sys.argv[1])
