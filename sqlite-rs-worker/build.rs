//! Compiles the C worker's pinned SQLite amalgamation into this binary with
//! exactly the C worker's compile options, so the two workers run the same
//! SQLite: `SQLITE_DEFS` and `OPT` are read from cworker/Makefile (not
//! copied), and the source is cworker/vendor/, which that Makefile downloads
//! and checks against its SHA-256. The C compiler is invoked directly (`$CC`,
//! default `cc`) and the object archived with `ar`: no `cc` crate.
//!
//! Also generates `errnames.rs` (result code -> "SQLITE_..." name) from the
//! amalgamation's sqlite3.h, with the rules of cworker/gen_errnames.py.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const VERSION: &str = "3530100";

fn makefile_var(text: &str, name: &str) -> String {
    let mut out = String::new();
    let mut lines = text.lines();
    while let Some(line) = lines.next() {
        let Some(rest) = line.strip_prefix(name) else { continue };
        let rest = rest.trim_start();
        let Some(rest) = rest.strip_prefix(":=").or_else(|| rest.strip_prefix("?=")) else { continue };
        let mut cur = rest.to_string();
        loop {
            let cont = cur.trim_end().ends_with('\\');
            out.push_str(cur.trim_end().trim_end_matches('\\'));
            out.push(' ');
            if !cont {
                break;
            }
            cur = lines.next().unwrap_or("").to_string();
        }
        return out.split_whitespace().collect::<Vec<_>>().join(" ");
    }
    panic!("{name} not found in cworker/Makefile");
}

fn run(cmd: &mut Command) {
    let status = cmd.status().unwrap_or_else(|e| panic!("cannot run {cmd:?}: {e}"));
    assert!(status.success(), "{cmd:?} failed: {status}");
}

fn errnames(header: &Path, out: &Path) {
    let text = fs::read_to_string(header).expect("read sqlite3.h");
    let start = text.find("#define SQLITE_OK ").expect("SQLITE_OK in sqlite3.h");
    let end = text.find("#define SQLITE_OK_SYMLINK").expect("SQLITE_OK_SYMLINK in sqlite3.h");
    let mut table: Vec<(String, i64)> = Vec::new();
    for line in text[start..end].lines() {
        let Some(rest) = line.strip_prefix("#define ") else { continue };
        let mut parts = rest.splitn(2, char::is_whitespace);
        let name = parts.next().unwrap_or("").to_string();
        if !name.starts_with("SQLITE_") || name == "SQLITE_OK_LOAD_PERMANENTLY" {
            continue;
        }
        let body = parts.next().unwrap_or("");
        let body = body.split("/*").next().unwrap_or("").trim();
        let value = if let Ok(v) = body.parse::<i64>() {
            v
        } else {
            // (SQLITE_BASE | (N<<8))
            let inner = body.trim_start_matches('(').trim_end_matches(')');
            let (base, shift) = inner.split_once('|').unwrap_or_else(|| panic!("cannot parse {line}"));
            let base = base.trim();
            let n: i64 = shift
                .trim()
                .trim_start_matches('(')
                .split("<<")
                .next()
                .unwrap()
                .trim()
                .parse()
                .unwrap_or_else(|_| panic!("cannot parse {line}"));
            let b = table.iter().find(|(k, _)| k == base).unwrap_or_else(|| panic!("unknown {base}")).1;
            b | (n << 8)
        };
        table.push((name, value));
    }
    let mut s = String::from("// Generated by build.rs from sqlite3.h: result code names.\n");
    s.push_str("pub static ERRNAMES: &[(i32, &str)] = &[\n");
    for (k, v) in &table {
        s.push_str(&format!("    ({v}, \"{k}\"),\n"));
    }
    s.push_str("];\n");
    fs::write(out, s).expect("write errnames.rs");
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let cworker = manifest.join("..").join("cworker");
    let makefile = cworker.join("Makefile");
    let dir = cworker.join("vendor").join(format!("sqlite-amalgamation-{VERSION}"));
    let src = dir.join("sqlite3.c");
    println!("cargo:rerun-if-changed={}", makefile.display());
    println!("cargo:rerun-if-changed={}", src.display());
    println!("cargo:rerun-if-env-changed=CC");
    if !src.is_file() {
        panic!(
            "{} is missing: run `make -C cworker vendor/sqlite-amalgamation-{VERSION}/sqlite3.c` \
             (or `make -C sqlite-rs-worker`, which does it)",
            src.display()
        );
    }
    let mk = fs::read_to_string(&makefile).expect("read cworker/Makefile");
    let defs = makefile_var(&mk, "SQLITE_DEFS");
    let opt = makefile_var(&mk, "OPT");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let obj = out.join("sqlite3.o");
    let lib = out.join("libdblsqlite3.a");
    let cc = env::var("CC").unwrap_or_else(|_| "cc".into());
    let mut cmd = Command::new(&cc);
    cmd.args(opt.split_whitespace()).args(defs.split_whitespace());
    // A sanitizer build of the Rust code (RUSTFLAGS=-Zsanitizer=thread or
    // =address, nightly) instruments SQLite too, as `make -C cworker
    // SANITIZE=...` does: otherwise TSan cannot see SQLite's own memory
    // accesses and a clean run would mean nothing. The sanitizer runtime is
    // the one rustc links.
    println!("cargo:rerun-if-env-changed=CARGO_ENCODED_RUSTFLAGS");
    let rustflags = env::var("CARGO_ENCODED_RUSTFLAGS").unwrap_or_default();
    let sanitize = env::var("CARGO_CFG_SANITIZE").unwrap_or_default();
    for (name, flag) in [("thread", "-fsanitize=thread"), ("address", "-fsanitize=address")] {
        if sanitize.split(',').any(|s| s == name) || rustflags.contains(&format!("-Zsanitizer={name}")) {
            cmd.arg(flag).arg("-fno-omit-frame-pointer");
            println!("cargo:warning=SQLite compiled with {flag}");
        }
    }
    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
        cmd.arg("-fPIC");
    }
    cmd.arg("-c").arg("-o").arg(&obj).arg(&src);
    run(&mut cmd);
    let _ = fs::remove_file(&lib);
    run(Command::new(env::var("AR").unwrap_or_else(|_| "ar".into())).arg("crs").arg(&lib).arg(&obj));
    println!("cargo:rustc-link-search=native={}", out.display());
    println!("cargo:rustc-link-lib=static=dblsqlite3");
    println!("cargo:rustc-link-lib=m");
    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
        println!("cargo:rustc-link-lib=dl");
        println!("cargo:rustc-link-lib=pthread");
    }
    // Recorded for `--version` and the report: what this build used.
    println!("cargo:rustc-env=DBL_SQLITE_CFLAGS={opt} {defs}");
    errnames(&dir.join("sqlite3.h"), &out.join("errnames.rs"));
}
