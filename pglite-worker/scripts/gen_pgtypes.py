"""Regenerate pglite-worker/src/pgtypes.mjs from psycopg's built-in type
registry, so result column types are named exactly as the psycopg backend
names them (``uv run --extra psycopg python pglite-worker/scripts/gen_pgtypes.py``)."""

import json
from pathlib import Path

import psycopg
from psycopg.postgres import types

names: dict[int, str] = {}
elements: dict[int, int] = {}
for info in set(types):
    names[info.oid] = info.name
    if info.array_oid:
        names[info.array_oid] = info.name
        elements[info.array_oid] = info.oid

out = Path(__file__).resolve().parent.parent / "src" / "pgtypes.mjs"
out.write_text(
    f"// Generated by scripts/gen_pgtypes.py from psycopg {psycopg.__version__}'s built-in types:\n"
    "// the names the psycopg backend reports for result columns (an array\n"
    "// type is named as its element, as psycopg does), and each array type's\n"
    "// element type. Types missing here (user-defined, unknown) have no name.\n\n"
    f"export const TYPE_NAMES = new Map({json.dumps(sorted(names.items()))});\n\n"
    f"export const ARRAY_ELEMENTS = new Map({json.dumps(sorted(elements.items()))});\n"
)
print(f"wrote {out} ({len(names)} names, {len(elements)} array types)")
